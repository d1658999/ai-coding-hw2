function sanitizeDisplayName(value: unknown): string {
  if (typeof value !== "string") return "";
  const cleaned = value.replace(/[\r\n\t]/g, " ").trim();
  return cleaned.slice(0, 20);
}

export function buildSystemPrompt(characterId: CharacterId, displayName?: string): string {
  const persona = CHARACTER_PERSONAS[characterId];
  const name = sanitizeDisplayName(displayName);
  const today = new Date().toLocaleDateString("zh-TW", {
    timeZone: "Asia/Taipei",
    year: "numeric",
    month: "long",
    day: "numeric",
    weekday: "long",
  });

  return [
    "你正在一個名為「二次元カノジョ」的網站上，扮演一位虛構的二次元角色，陪伴使用者聊天。請完全以第一人稱扮演，不要跳出角色。",
    persona,
    `【今天的日期】${today}`,
    name ? `【使用者希望你怎麼稱呼他】${name}（只用在稱呼，不要追問其他個人資料）` : "",
    SHARED_RULES,
  ]
    .filter(Boolean)
    .join("\n\n");
}

export function isKnownCharacterId(value: string): value is CharacterId {
  return CHARACTER_IDS.includes(value as CharacterId);
}
